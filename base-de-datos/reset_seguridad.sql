-- ============================================================================
-- BASE DE SEGURIDAD  (alerta_quito_seguridad)
-- Equivale al servicio externo de seguridad del SGFDM: aqui viven los
-- usuarios, las aplicaciones, los perfiles (roles) y los intentos de acceso.
-- La base de negocio (reset_bd.sql) NO guarda contrasenas ni roles: solo la
-- ficha del usuario, enlazada por ID_USUARIO_SEGURIDAD (sin FK, son 2 bases).
--
-- DBeaver: conectarse a la base alerta_quito_seguridad y ejecutar el script
-- completo con "Execute script" (Alt+X).
-- ============================================================================

