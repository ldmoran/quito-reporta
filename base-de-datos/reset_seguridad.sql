-- ============================================
-- 2. CREAR TABLAS
-- ============================================

-- Sistemas que usan este login (hoy solo ALQ = Alerta Quito). Permite que otro
-- sistema reutilice la misma base de seguridad con sus propios perfiles.
CREATE TABLE aplicacion (
    id_aplicacion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo         VARCHAR(10)  NOT NULL UNIQUE,
    nombre         VARCHAR(100) NOT NULL,
    estado         CHAR(1) NOT NULL DEFAULT 'A' CHECK (estado IN ('A', 'I'))
);

-- Perfiles (roles) de cada aplicacion. El codigo de 6 letras se convierte en
-- la autoridad ROLE_<codigo> de Spring Security, igual que en el SGFDM
-- (REGING, FLUCAJ, ...).
CREATE TABLE perfil (
    id_perfil      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aplicacion  INTEGER      NOT NULL REFERENCES aplicacion(id_aplicacion),
    codigo         VARCHAR(10)  NOT NULL,
    nombre         VARCHAR(100) NOT NULL,
    descripcion    VARCHAR(300),
    estado         CHAR(1) NOT NULL DEFAULT 'A' CHECK (estado IN ('A', 'I')),
    CONSTRAINT uq_perfil_app_codigo UNIQUE (id_aplicacion, codigo)
);

CREATE TABLE usuario (
    id_usuario        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario           VARCHAR(50)  NOT NULL UNIQUE,    -- nombre de login
    nombre_completo   VARCHAR(150) NOT NULL,
    cedula            VARCHAR(13),
    correo            VARCHAR(150) NOT NULL UNIQUE,
    password_hash     VARCHAR(100) NOT NULL,           -- bcrypt, nunca texto plano
    estado            CHAR(1) NOT NULL DEFAULT 'A' CHECK (estado IN ('A', 'I')),
    intentos_fallidos SMALLINT NOT NULL DEFAULT 0,
    bloqueado         BOOLEAN  NOT NULL DEFAULT FALSE, -- lo activa el trigger al 3er fallo
    -- TRUE cuando el administrador creo o restablecio la clave: la persona debe cambiarla
    -- en su proximo ingreso y mientras tanto el API solo le deja usar /api/auth/cambiar-password.
    debe_cambiar_password BOOLEAN NOT NULL DEFAULT FALSE,
    ultimo_acceso     TIMESTAMP,
    fecha_creacion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Que perfiles tiene cada usuario (un usuario puede tener varios).
CREATE TABLE usuario_perfil (
    id_usuario  INTEGER NOT NULL REFERENCES usuario(id_usuario),
    id_perfil   INTEGER NOT NULL REFERENCES perfil(id_perfil),
    CONSTRAINT pk_usuario_perfil PRIMARY KEY (id_usuario, id_perfil)
);

-- Bitacora de cada intento de login (correcto o no). A proposito SIN trigger
-- de auditoria: se escribe en cada inicio de sesion y llenaria AUDITORIA de ruido.
CREATE TABLE intento_acceso (
    id_intento  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario     VARCHAR(50) NOT NULL,
    exitoso     BOOLEAN     NOT NULL,
    motivo      VARCHAR(100),
    fecha       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- "Olvide mi contrasena": el usuario pide un enlace por correo. Del enlace solo se guarda el HASH (SHA-256)
-- del token, nunca el token en claro: quien lea esta tabla no puede restablecer cuentas ajenas.
-- Cada token sirve una sola vez y vence a los 30 minutos. A proposito SIN trigger de auditoria (como
-- INTENTO_ACCESO); el cambio de clave en si queda registrado por el trigger de USUARIO.
CREATE TABLE restablecimiento_password (
    id_restablecimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario          INTEGER   NOT NULL REFERENCES usuario(id_usuario),
    token_hash          CHAR(64)  NOT NULL UNIQUE,
    fecha_creacion      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_expiracion    TIMESTAMP NOT NULL,
    usado               BOOLEAN   NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_restablecimiento_usuario ON restablecimiento_password(id_usuario, fecha_creacion);

-- ============================================
-- 2.1 HISTORIAL Y AUDITORIA (mismo patron que el SGFDM)
--     *_HIST   : copia de la fila en cada INSERT/UPDATE/DELETE.
--     AUDITORIA: una sola tabla con quien hizo que, en que tabla y cuando.
--     La contrasena NO se copia al historial.
-- ============================================
CREATE TABLE usuario_hist (
    id_hist         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion       VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion  VARCHAR(50),
    fecha_accion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_usuario      INTEGER,
    usuario         VARCHAR(50),
    nombre_completo VARCHAR(150),
    correo          VARCHAR(150),
    estado          CHAR(1),
    bloqueado       BOOLEAN
);

CREATE TABLE perfil_hist (
    id_hist         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion       VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion  VARCHAR(50),
    fecha_accion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_perfil       INTEGER,
    id_aplicacion   INTEGER,
    codigo          VARCHAR(10),
    nombre          VARCHAR(100),
    estado          CHAR(1)
);

CREATE TABLE auditoria (
    id_auditoria    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tabla    VARCHAR(50) NOT NULL,
    id_registro     VARCHAR(50),
    accion          VARCHAR(10) NOT NULL CHECK (accion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion  VARCHAR(50),
    fecha_accion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    descripcion     VARCHAR(500)
);

-- ============================================
-- 3. FUNCIONES Y TRIGGERS
-- ============================================

-- Quien hizo el cambio. La app usa un unico usuario tecnico de conexion, asi
-- que antes de guardar ejecuta  SELECT set_config('app.usuario', '<login>', true)
-- (equivale al DBMS_SESSION.SET_IDENTIFIER de Oracle). Si no se puso (ej. un
-- UPDATE a mano en DBeaver) cae al usuario de la conexion.
CREATE OR REPLACE FUNCTION fn_usuario_sesion() RETURNS VARCHAR
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('app.usuario', true), ''), current_user)::VARCHAR
$$;

-- Bloqueo tras 3 intentos fallidos. Un login correcto pone intentos_fallidos
-- en 0 y NO desbloquea: solo el administrador desbloquea (bloqueado = FALSE).
CREATE OR REPLACE FUNCTION fn_usuario_bloqueo() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.bloqueado AND NOT NEW.bloqueado THEN
        NEW.intentos_fallidos := 0;     -- al desbloquear se reinicia el contador
    ELSIF NEW.intentos_fallidos >= 3 THEN
        NEW.bloqueado := TRUE;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_usuario_bloqueo
BEFORE UPDATE ON usuario
FOR EACH ROW EXECUTE FUNCTION fn_usuario_bloqueo();

-- Auditoria de USUARIO. No audita el simple contador de intentos / ultimo
-- acceso (seria ruido en cada login): solo altas, bajas y cambios de datos,
-- estado, bloqueo o contrasena.
CREATE OR REPLACE FUNCTION fn_usuario_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario VARCHAR := fn_usuario_sesion();
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO usuario_hist (operacion, usuario_accion, id_usuario, usuario, nombre_completo, correo, estado, bloqueado)
        VALUES ('INSERT', v_usuario, NEW.id_usuario, NEW.usuario, NEW.nombre_completo, NEW.correo, NEW.estado, NEW.bloqueado);
        INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
        VALUES ('USUARIO', NEW.id_usuario, 'INSERT', v_usuario, 'Usuario creado');
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        IF (NEW.nombre_completo, NEW.cedula, NEW.correo, NEW.estado, NEW.bloqueado, NEW.password_hash)
           IS DISTINCT FROM
           (OLD.nombre_completo, OLD.cedula, OLD.correo, OLD.estado, OLD.bloqueado, OLD.password_hash) THEN
            INSERT INTO usuario_hist (operacion, usuario_accion, id_usuario, usuario, nombre_completo, correo, estado, bloqueado)
            VALUES ('UPDATE', v_usuario, NEW.id_usuario, NEW.usuario, NEW.nombre_completo, NEW.correo, NEW.estado, NEW.bloqueado);
            INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
            VALUES ('USUARIO', NEW.id_usuario, 'UPDATE', v_usuario,
                    CASE WHEN NEW.bloqueado AND NOT OLD.bloqueado THEN 'Usuario bloqueado'
                         WHEN OLD.bloqueado AND NOT NEW.bloqueado THEN 'Usuario desbloqueado'
                         WHEN NEW.estado <> OLD.estado THEN
                              CASE WHEN NEW.estado = 'I' THEN 'Usuario dado de baja' ELSE 'Usuario dado de alta' END
                         WHEN NEW.password_hash <> OLD.password_hash THEN 'Cambio de contrasena'
                         ELSE 'Datos personales actualizados'
                    END);
        END IF;
        RETURN NEW;
    ELSE
        INSERT INTO usuario_hist (operacion, usuario_accion, id_usuario, usuario, nombre_completo, correo, estado, bloqueado)
        VALUES ('DELETE', v_usuario, OLD.id_usuario, OLD.usuario, OLD.nombre_completo, OLD.correo, OLD.estado, OLD.bloqueado);
        INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
        VALUES ('USUARIO', OLD.id_usuario, 'DELETE', v_usuario, 'Usuario eliminado');
        RETURN OLD;
    END IF;
END;
$$;

CREATE TRIGGER trg_usuario_audit
AFTER INSERT OR UPDATE OR DELETE ON usuario
FOR EACH ROW EXECUTE FUNCTION fn_usuario_audit();

CREATE OR REPLACE FUNCTION fn_perfil_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario VARCHAR := fn_usuario_sesion();
    r         perfil%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN r := OLD; ELSE r := NEW; END IF;
    INSERT INTO perfil_hist (operacion, usuario_accion, id_perfil, id_aplicacion, codigo, nombre, estado)
    VALUES (TG_OP, v_usuario, r.id_perfil, r.id_aplicacion, r.codigo, r.nombre, r.estado);
    INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
    VALUES ('PERFIL', r.id_perfil, TG_OP,
            v_usuario, CASE TG_OP WHEN 'INSERT' THEN 'Perfil creado' WHEN 'DELETE' THEN 'Perfil eliminado' ELSE 'Perfil actualizado' END);
    RETURN r;
END;
$$;

CREATE TRIGGER trg_perfil_audit
AFTER INSERT OR UPDATE OR DELETE ON perfil
FOR EACH ROW EXECUTE FUNCTION fn_perfil_audit();

-- Quien le dio o le quito un perfil a quien (tabla puente, solo AUDITORIA).
CREATE OR REPLACE FUNCTION fn_usuario_perfil_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    r usuario_perfil%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN r := OLD; ELSE r := NEW; END IF;
    INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
    VALUES ('USUARIO_PERFIL', r.id_usuario, TG_OP, fn_usuario_sesion(),
            CASE TG_OP WHEN 'INSERT' THEN 'Perfil asignado: ' ELSE 'Perfil retirado: ' END || r.id_perfil);
    RETURN r;
END;
$$;

CREATE TRIGGER trg_usuario_perfil_audit
AFTER INSERT OR DELETE ON usuario_perfil
FOR EACH ROW EXECUTE FUNCTION fn_usuario_perfil_audit();

