    operacion       VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion  VARCHAR(50),
    fecha_accion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_entidad      INTEGER,
    codigo          VARCHAR(10),
    nombre          VARCHAR(150),
    descripcion     VARCHAR(300),
    estado          CHAR(1)
);

CREATE TABLE tipo_incidente_hist (
    id_hist            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion          VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion     VARCHAR(50),
    fecha_accion       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_tipo_incidente  INTEGER,
    id_entidad         INTEGER,
    nombre             VARCHAR(100),
    prioridad_base     SMALLINT,
    es_emergencia      BOOLEAN,
    estado             CHAR(1)
);

CREATE TABLE funcionario_hist (
    id_hist         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operacion       VARCHAR(10) NOT NULL CHECK (operacion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion  VARCHAR(50),
    fecha_accion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    id_funcionario  INTEGER,
    id_usuario      INTEGER,
    id_entidad      INTEGER,
    cargo           VARCHAR(100),
    estado          CHAR(1)
);

CREATE TABLE auditoria (
    id_auditoria    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_tabla    VARCHAR(50) NOT NULL,
    id_registro     BIGINT,
    accion          VARCHAR(10) NOT NULL CHECK (accion IN ('INSERT', 'UPDATE', 'DELETE')),
    usuario_accion  VARCHAR(50),
    fecha_accion    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    descripcion     VARCHAR(500)
);

-- ============================================
-- 3. FUNCIONES Y TRIGGERS
-- ============================================

-- Quien hizo el cambio: la app ejecuta  SELECT set_config('app.usuario', '<login>', true)
-- antes de guardar. Si no se puso (UPDATE a mano en DBeaver) cae al usuario de conexion.
CREATE OR REPLACE FUNCTION fn_usuario_sesion() RETURNS VARCHAR
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(NULLIF(current_setting('app.usuario', true), ''), current_user)::VARCHAR
$$;

-- ---------- REPORTE ----------

-- Antes de insertar: numero de reporte (RF-01) y prioridad segun el tipo (RF-03).
CREATE OR REPLACE FUNCTION fn_reporte_antes_insertar() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    NEW.codigo    := 'RQ-' || to_char(CURRENT_DATE, 'YYYY') || '-' || lpad(nextval('seq_reporte_codigo')::TEXT, 6, '0');
    NEW.prioridad := (SELECT prioridad_base FROM tipo_incidente WHERE id_tipo_incidente = NEW.id_tipo_incidente);
    NEW.estado    := 'REGISTRADO';
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reporte_antes_insertar
BEFORE INSERT ON reporte
FOR EACH ROW EXECUTE FUNCTION fn_reporte_antes_insertar();

-- Despues de insertar: derivacion automatica a la entidad del tipo (RF-03) y
-- primera linea del historial.
CREATE OR REPLACE FUNCTION fn_reporte_despues_insertar() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO derivacion (id_reporte, id_entidad)
    SELECT NEW.id_reporte, id_entidad FROM tipo_incidente WHERE id_tipo_incidente = NEW.id_tipo_incidente;

    INSERT INTO historial_estado (id_reporte, estado_anterior, estado_nuevo, usuario_accion, comentario)
    VALUES (NEW.id_reporte, NULL, 'REGISTRADO',
            (SELECT usuario FROM usuario WHERE id_usuario = NEW.id_ciudadano), 'Reporte creado');
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reporte_despues_insertar
AFTER INSERT ON reporte
FOR EACH ROW EXECUTE FUNCTION fn_reporte_despues_insertar();

-- Un reporte sin foto no puede existir (RF-04). Es un constraint trigger
-- DEFERRED: se revisa al COMMIT, para que la app pueda insertar primero el
-- reporte y luego la evidencia dentro de la misma transaccion.
CREATE OR REPLACE FUNCTION fn_reporte_exige_foto() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM evidencia WHERE id_reporte = NEW.id_reporte AND tipo = 'CREACION') THEN
        RAISE EXCEPTION 'El reporte % no tiene la foto de evidencia obligatoria', NEW.codigo
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER trg_reporte_exige_foto
AFTER INSERT ON reporte
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION fn_reporte_exige_foto();

-- Antes de actualizar: solo transiciones validas, no se reabre un caso cerrado
-- y no se puede RESOLVER sin foto de resolucion (RF-04).
--   REGISTRADO  -> EN_REVISION | EN_ATENCION | RECHAZADO
--   EN_REVISION -> EN_ATENCION | RECHAZADO
--   EN_ATENCION -> RESUELTO
CREATE OR REPLACE FUNCTION fn_reporte_antes_actualizar() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        IF NOT (   (OLD.estado = 'REGISTRADO'  AND NEW.estado IN ('EN_REVISION', 'EN_ATENCION', 'RECHAZADO'))
                OR (OLD.estado = 'EN_REVISION' AND NEW.estado IN ('EN_ATENCION', 'RECHAZADO'))
                OR (OLD.estado = 'EN_ATENCION' AND NEW.estado = 'RESUELTO')) THEN
            RAISE EXCEPTION 'Transicion de estado no permitida: % -> %', OLD.estado, NEW.estado
                USING ERRCODE = 'check_violation';
        END IF;

        IF NEW.estado = 'RESUELTO'
           AND NOT EXISTS (SELECT 1 FROM evidencia WHERE id_reporte = NEW.id_reporte AND tipo = 'RESOLUCION') THEN
            RAISE EXCEPTION 'No se puede resolver el reporte % sin evidencia de resolucion', OLD.codigo
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;

    -- Campos que nadie debe cambiar a mano despues de crear el reporte.
    NEW.codigo            := OLD.codigo;
    NEW.id_ciudadano      := OLD.id_ciudadano;
    NEW.id_tipo_incidente := OLD.id_tipo_incidente;
    NEW.prioridad         := OLD.prioridad;
    NEW.fecha_creacion    := OLD.fecha_creacion;
    NEW.fecha_actualizacion := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reporte_antes_actualizar
BEFORE UPDATE ON reporte
FOR EACH ROW EXECUTE FUNCTION fn_reporte_antes_actualizar();

-- Despues de actualizar: una fila en HISTORIAL_ESTADO por cada cambio de estado.
CREATE OR REPLACE FUNCTION fn_reporte_despues_actualizar() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado IS DISTINCT FROM OLD.estado THEN
        INSERT INTO historial_estado (id_reporte, estado_anterior, estado_nuevo, usuario_accion, comentario)
        VALUES (NEW.id_reporte, OLD.estado, NEW.estado,
                COALESCE(NEW.actualizado_por, fn_usuario_sesion()), NEW.comentario_estado);
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_reporte_despues_actualizar
AFTER UPDATE ON reporte
FOR EACH ROW EXECUTE FUNCTION fn_reporte_despues_actualizar();

-- Evidencia: es prueba, no se modifica ni se borra.
CREATE OR REPLACE FUNCTION fn_evidencia_inmutable() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
BEGIN
    -- Si el reporte ya no existe, es el borrado en cascada de un reporte (o un
    -- reset): se permite. Mientras el reporte exista, la evidencia es intocable.
    IF TG_OP = 'DELETE' AND NOT EXISTS (SELECT 1 FROM reporte WHERE id_reporte = OLD.id_reporte) THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'La evidencia no se puede modificar ni eliminar'
        USING ERRCODE = 'check_violation';
END;
$$;

CREATE TRIGGER trg_evidencia_inmutable
BEFORE UPDATE OR DELETE ON evidencia
FOR EACH ROW EXECUTE FUNCTION fn_evidencia_inmutable();

-- ---------- MANTENIMIENTO: HIST + AUDITORIA ----------

CREATE OR REPLACE FUNCTION fn_entidad_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario VARCHAR := fn_usuario_sesion();
    r         entidad%ROWTYPE;
    v_desc    VARCHAR;
BEGIN
    IF TG_OP = 'DELETE' THEN r := OLD; ELSE r := NEW; END IF;
    v_desc := CASE TG_OP WHEN 'INSERT' THEN 'Entidad creada' WHEN 'DELETE' THEN 'Entidad eliminada'
                         ELSE CASE WHEN NEW.estado <> OLD.estado THEN
                                   CASE WHEN NEW.estado = 'I' THEN 'Entidad desactivada' ELSE 'Entidad activada' END
                              ELSE 'Datos de la entidad actualizados' END END;
    INSERT INTO entidad_hist (operacion, usuario_accion, id_entidad, codigo, nombre, descripcion, estado)
    VALUES (TG_OP, v_usuario, r.id_entidad, r.codigo, r.nombre, r.descripcion, r.estado);
    INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
    VALUES ('ENTIDAD', r.id_entidad, TG_OP, v_usuario, v_desc);
    RETURN r;
END;
$$;

CREATE TRIGGER trg_entidad_audit
AFTER INSERT OR UPDATE OR DELETE ON entidad
FOR EACH ROW EXECUTE FUNCTION fn_entidad_audit();

CREATE OR REPLACE FUNCTION fn_tipo_incidente_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario VARCHAR := fn_usuario_sesion();
    r         tipo_incidente%ROWTYPE;
    v_desc    VARCHAR;
BEGIN
    IF TG_OP = 'DELETE' THEN r := OLD; ELSE r := NEW; END IF;
    v_desc := CASE TG_OP WHEN 'INSERT' THEN 'Tipo de incidente creado' WHEN 'DELETE' THEN 'Tipo de incidente eliminado'
                         ELSE CASE WHEN NEW.estado <> OLD.estado THEN
                                   CASE WHEN NEW.estado = 'I' THEN 'Tipo de incidente desactivado' ELSE 'Tipo de incidente activado' END
                              ELSE 'Datos del tipo de incidente actualizados' END END;
    INSERT INTO tipo_incidente_hist (operacion, usuario_accion, id_tipo_incidente, id_entidad, nombre, prioridad_base, es_emergencia, estado)
    VALUES (TG_OP, v_usuario, r.id_tipo_incidente, r.id_entidad, r.nombre, r.prioridad_base, r.es_emergencia, r.estado);
    INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
    VALUES ('TIPO_INCIDENTE', r.id_tipo_incidente, TG_OP, v_usuario, v_desc);
    RETURN r;
END;
$$;

CREATE TRIGGER trg_tipo_incidente_audit
AFTER INSERT OR UPDATE OR DELETE ON tipo_incidente
FOR EACH ROW EXECUTE FUNCTION fn_tipo_incidente_audit();

CREATE OR REPLACE FUNCTION fn_funcionario_audit() RETURNS TRIGGER
LANGUAGE plpgsql AS $$
DECLARE
    v_usuario VARCHAR := fn_usuario_sesion();
    r         funcionario%ROWTYPE;
    v_desc    VARCHAR;
BEGIN
    IF TG_OP = 'DELETE' THEN r := OLD; ELSE r := NEW; END IF;
    v_desc := CASE TG_OP WHEN 'INSERT' THEN 'Funcionario designado' WHEN 'DELETE' THEN 'Funcionario eliminado'
                         ELSE CASE WHEN NEW.estado <> OLD.estado THEN
                                   CASE WHEN NEW.estado = 'I' THEN 'Funcionario dado de baja' ELSE 'Funcionario dado de alta' END
                              WHEN NEW.id_entidad <> OLD.id_entidad THEN 'Funcionario cambiado de entidad'
                              ELSE 'Datos del funcionario actualizados' END END;
    INSERT INTO funcionario_hist (operacion, usuario_accion, id_funcionario, id_usuario, id_entidad, cargo, estado)
    VALUES (TG_OP, v_usuario, r.id_funcionario, r.id_usuario, r.id_entidad, r.cargo, r.estado);
    INSERT INTO auditoria (nombre_tabla, id_registro, accion, usuario_accion, descripcion)
    VALUES ('FUNCIONARIO', r.id_funcionario, TG_OP, v_usuario, v_desc);
    RETURN r;
END;
$$;

CREATE TRIGGER trg_funcionario_audit
AFTER INSERT OR UPDATE OR DELETE ON funcionario
FOR EACH ROW EXECUTE FUNCTION fn_funcionario_audit();

