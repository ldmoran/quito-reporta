-- ============================================
-- 2. CREAR TABLAS
-- ============================================

-- Ficha de quienes han entrado al sistema. Los usuarios NO se crean aqui: existen
-- en la base de seguridad. Esta tabla guarda una copia de nombre/correo para no
-- consultar la otra base en cada pantalla (se actualiza en cada inicio de sesion).
-- A proposito SIN trigger de auditoria: se escribe en cada login y seria ruido.
CREATE TABLE usuario (
    id_usuario            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_seguridad  INTEGER      NOT NULL UNIQUE,   -- usuario.id_usuario de la base de seguridad
    usuario               VARCHAR(50)  NOT NULL,
    nombre_completo       VARCHAR(150) NOT NULL,
    correo                VARCHAR(150),
    ultimo_acceso         TIMESTAMP
);

-- ------------------------------------------------------------------
-- Tablas de MANTENIMIENTO (catalogos que administra el ADMINISTRADOR):
-- ENTIDAD, TIPO_INCIDENTE y FUNCIONARIO. Cada una tiene su tabla *_HIST y
-- un trigger que escribe tambien en AUDITORIA (seccion 2.1 y 3).
-- ------------------------------------------------------------------

-- Entidades de respuesta (EPMMOP, AMT, EEQ, Policia, Bomberos).
CREATE TABLE entidad (
    id_entidad   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo       VARCHAR(10)  NOT NULL UNIQUE,
    nombre       VARCHAR(150) NOT NULL,
    descripcion  VARCHAR(300),
    estado       CHAR(1) NOT NULL DEFAULT 'A' CHECK (estado IN ('A', 'I'))
);

-- Tipo de incidente -> entidad competente + prioridad base.
-- prioridad: 1 = critica (emergencia), 2 = alta, 3 = media, 4 = baja.
CREATE TABLE tipo_incidente (
    id_tipo_incidente  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_entidad         INTEGER      NOT NULL REFERENCES entidad(id_entidad),
    nombre             VARCHAR(100) NOT NULL UNIQUE,
    prioridad_base     SMALLINT     NOT NULL CHECK (prioridad_base BETWEEN 1 AND 4),
    es_emergencia      BOOLEAN      NOT NULL DEFAULT FALSE,
    estado             CHAR(1) NOT NULL DEFAULT 'A' CHECK (estado IN ('A', 'I'))
);

-- Persona designada por una entidad. Solo la registra el administrador.
CREATE TABLE funcionario (
    id_funcionario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario         INTEGER NOT NULL UNIQUE REFERENCES usuario(id_usuario),
    id_entidad         INTEGER NOT NULL REFERENCES entidad(id_entidad),
    cargo              VARCHAR(100),
    estado             CHAR(1) NOT NULL DEFAULT 'A' CHECK (estado IN ('A', 'I')),
    fecha_designacion  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------------
-- Reportes
-- ------------------------------------------------------------------
CREATE SEQUENCE seq_reporte_codigo START 1;

CREATE TABLE reporte (
    id_reporte          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(20) UNIQUE,                 -- lo pone el trigger: RQ-2026-000001
    id_ciudadano        INTEGER NOT NULL REFERENCES usuario(id_usuario),
    id_tipo_incidente   INTEGER NOT NULL REFERENCES tipo_incidente(id_tipo_incidente),
    descripcion         VARCHAR(500),
    prioridad           SMALLINT CHECK (prioridad BETWEEN 1 AND 4),   -- la pone el trigger
    estado              VARCHAR(15) NOT NULL DEFAULT 'REGISTRADO'
                        CHECK (estado IN ('REGISTRADO', 'EN_REVISION', 'EN_ATENCION', 'RESUELTO', 'RECHAZADO')),
    comentario_estado   VARCHAR(500),   -- la app lo llena al cambiar de estado; el trigger lo copia al historial
    actualizado_por     VARCHAR(50),    -- idem: login de quien cambio el estado
    fecha_creacion      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_reporte_ciudadano ON reporte(id_ciudadano);
CREATE INDEX idx_reporte_tipo      ON reporte(id_tipo_incidente);
CREATE INDEX idx_reporte_estado    ON reporte(estado);

-- Ubicacion exacta. El CHECK deja fuera lo que no es del Distrito Metropolitano
-- de Quito (prueba del PDF: "reporte fuera de Quito").
CREATE TABLE ubicacion (
    id_ubicacion  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte    BIGINT NOT NULL UNIQUE REFERENCES reporte(id_reporte) ON DELETE CASCADE,
    latitud       NUMERIC(9,6) NOT NULL CHECK (latitud  BETWEEN -0.45 AND 0.20),
    longitud      NUMERIC(9,6) NOT NULL CHECK (longitud BETWEEN -78.80 AND -78.20),
    direccion     VARCHAR(250),
    referencia    VARCHAR(250)
);

-- A que entidad se envio el reporte (la crea el trigger al insertar el reporte).
CREATE TABLE derivacion (
    id_derivacion      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte         BIGINT  NOT NULL REFERENCES reporte(id_reporte) ON DELETE CASCADE,
    id_entidad         INTEGER NOT NULL REFERENCES entidad(id_entidad),
    fecha_derivacion   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_derivacion_entidad ON derivacion(id_entidad);

-- Cada cambio de estado con fecha y responsable (RF-04). Lo llena el trigger.
CREATE TABLE historial_estado (
    id_historial     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte       BIGINT NOT NULL REFERENCES reporte(id_reporte) ON DELETE CASCADE,
    estado_anterior  VARCHAR(15),
    estado_nuevo     VARCHAR(15) NOT NULL,
    usuario_accion   VARCHAR(50),
    comentario       VARCHAR(500),
    fecha            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_historial_reporte ON historial_estado(id_reporte);

-- Fotos. CREACION = la que sube el ciudadano; RESOLUCION = la que sube el
-- funcionario al cerrar el caso. Una evidencia no se edita ni se borra (trigger).
CREATE TABLE evidencia (
    id_evidencia   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reporte     BIGINT NOT NULL REFERENCES reporte(id_reporte) ON DELETE CASCADE,
    tipo           VARCHAR(10) NOT NULL CHECK (tipo IN ('CREACION', 'RESOLUCION')),
    nombre_archivo VARCHAR(200) NOT NULL,
    ruta_archivo   VARCHAR(400) NOT NULL,
    content_type   VARCHAR(100),
    subido_por     VARCHAR(50),
    fecha          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_evidencia_reporte ON evidencia(id_reporte);

-- ============================================
